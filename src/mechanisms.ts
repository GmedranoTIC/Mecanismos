/**
 * Normaliza IDs antiguos de mecanismos para compatibilidad retrospectiva
 */
export const normalizeMechId = (id: string): string => {
  if (id === 'pistola_cuerda') return 'canon';
  if (id === 'polea_multiple') return 'polea_simple';
  if (id === 'engranaje_conico' || id === 'engranaje_simple') return 'engranaje';
  return id;
};

